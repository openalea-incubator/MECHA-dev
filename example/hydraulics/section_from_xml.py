"""
A section read from an XML file (the original MECHA's tutorial 01, ported): an anatomy into MECHA, its radial
conductivity kr and axial conductance Kx at two maturity stages, and the views of its hydraulics.

In the port, MECHA is a metafspm component on the plant's DataStructure, and its anatomies come from GRANAP's
component, either generated (the root preset) or read from an XML file by GRANAP's CellSetOrgan (the legacy's own XML
builder is not ported, Q-M7): a CellSet file (a Brassicaceae root from GRANAP's tests), or GRANAR's current_root.xml,
the legacy tutorial's own section. The same section is then solved at barrier 1 (Casparian strip) and 3 (suberized
endodermis).

    python section_from_xml.py [cellset|granar]      (from MECHA-dev/example/hydraulics; figures in ./outputs/)
"""
import os
import sys

import matplotlib.pyplot as plt

from openalea.metafspm import CompositeModel, Planting, planting, Scene

from openalea.granap.cellset_organ import CellSetOrgan
from openalea.granap.metafspm.architectures import RootAxis
from openalea.granap.metafspm.component import GranapAnatomy, junction_rules
from openalea.granap.metafspm.library import AnatomyLibrary
from openalea.mecha import plots
from openalea.mecha.component import MechaHydraulics
from openalea.mecha.stand_ins import Development

HERE = os.path.dirname(os.path.abspath(__file__))
CELLSET = os.path.join(HERE, "inputs", "partial_CellSet_brasicaceae.xml")    # a CellSet file (µm), from GRANAP
GRANAR = os.path.join(HERE, "inputs", "current_root.xml")                     # GRANAR's output (mm)
FILES = {"cellset": CELLSET, "granar": GRANAR}
HEIGHT = 200e-6                                  # m: the legacy's default section height (200 µm)
RADIUS = 0.55e-3                                 # m
BARRIERS = (1, 3)


def cellset_organ_class(path, scale=None):
    """
    An organ class for GRANAP's library reading the XML at *path* (whatever the class's parameters); *scale*: the
    file's unit in mm, by default from its root element (GRANAR's files are in mm, CellSet's in µm: 0.001).
    """
    def organ(parameters, seed=0):
        return CellSetOrgan(path, scale=scale, seed=seed)
    return organ


def section_model(source):
    """One root segment (the section MECHA solves), its anatomy generated by GRANAP ("granap") or read from an XML
    file ("cellset", "granar"), its barrier (Development) and MECHA's hydraulics."""

    class Anatomy(GranapAnatomy):
        library = (AnatomyLibrary() if source == "granap" else
                   AnatomyLibrary(organ_class=cellset_organ_class(FILES[source])))

    class Section(CompositeModel):
        initiators = (RootAxis, Anatomy)
        from_scale, nodes, wiring = "SubOrgan", "Compartment", junction_rules
        parts = {"anatomy": Anatomy, "development": Development, "hydraulics": MechaHydraulics}
        schedule = ("development", "anatomy", "hydraulics")

    return Section


def main(source="granap"):
    model = section_model(source)
    frames = {}
    print(f"Hydraulic properties ({source}):")
    for barrier in BARRIERS:
        scenario = {"root_segments": [[RADIUS, HEIGHT, 0.]], "mature_barrier": float(barrier)}
        scene = Scene(planting([Planting()], model, scenario))
        scene.run()
        data_structure = scene.populations[0].data_structure
        mecha = scene.populations[0].instance.hydraulics
        segment = int(data_structure.entity_ids("SubOrgan")[0])
        print(f"  barrier {barrier} | kr = {data_structure.get('kr')[0]:.4e} cm hPa-1 d-1 | "
              f"Kx = {data_structure.get('Kx')[0]:.4e} cm4 hPa-1 d-1")
        frames[barrier] = plots.port_frame(mecha, segment)

    folder = os.path.join(HERE, "outputs")
    os.makedirs(folder, exist_ok=True)
    frame = frames[BARRIERS[-1]]
    fig, axes = plt.subplots(2, 3, figsize=(17, 11))
    plots.tissue_map(axes[0, 0], frame, title=f"the section ({source})")
    points = plots.psi_map(axes[0, 1], frame, title=f"water potential, barrier {BARRIERS[-1]}")
    fig.colorbar(points, ax=axes[0, 1], label="ψ (hPa)", shrink=0.8)
    for barrier, style in zip(BARRIERS, ("-", "--")):
        plots.radial_profile(axes[0, 2], frames[barrier], label=f"barrier {barrier}", linestyle=style)
    axes[0, 2].legend(fontsize=7)
    lines = plots.conductance_by_path(axes[1], frame)
    fig.colorbar(lines, ax=axes[1, :], label="log10 K (cm³ hPa⁻¹ d⁻¹)", shrink=0.8)
    fig.savefig(os.path.join(folder, f"section_from_xml_{source}_section.png"), dpi=300)
    plt.close(fig)

    fig, axes = plt.subplots(1, 3, figsize=(19, 6))
    plots.pathway_breakdown(axes[0], frame, title=f"pathways of the radial flow, barrier {BARRIERS[-1]}")
    plots.flow_vectors(axes[1], frame, "membrane")
    plots.flow_vectors(axes[2], frame, "plasmodesmata")
    fig.tight_layout()
    fig.savefig(os.path.join(folder, f"section_from_xml_{source}_flows.png"), dpi=300)
    plt.close(fig)
    print(folder)


if __name__ == "__main__":
    main(next((source for source in FILES if source in sys.argv[1:]), "granap"))
